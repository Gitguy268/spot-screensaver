// Traces a picture into layered vector shapes for the vector screensaver (maintainers only; the
// output in src/vector/traced/ is committed). Uses ImageMagick (CLI) to cut the white background
// away and scale, then imagetracerjs (public domain) to quantise colours and trace each colour.
//   node scripts/trace.mjs <in.png> <name> [height=760] [colours=24]
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync, mkdtempSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { PNG } from 'pngjs';

const require = createRequire(import.meta.url);
const ImageTracer = require('imagetracerjs');
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const [input, name, height = '760', colours = '24', fuzz = '5'] = process.argv.slice(2);
if (!input || !name) { console.error('usage: node scripts/trace.mjs <in.png> <name> [height] [colours] [fuzz%]'); process.exit(1); }

const tmp = join(mkdtempSync(join(tmpdir(), 'spot-trace-')), 'cut.png');
// background (white, connected to the corners) → transparent; trim; scale; a touch of smoothing
// frames that already have a transparent background (KEEP_FRAME=1) keep their size so they line up
const cut = process.env.KEEP_FRAME ? [] : ['-fuzz', `${fuzz}%`, '-fill', 'none', '-draw', 'color 1,1 floodfill', '-draw', `color %[fx:w-2],1 floodfill`,
  '-channel', 'A', '-morphology', 'Erode', 'Disk:1.5', '+channel', '-trim', '+repage'];
execFileSync('magick', [input, '-alpha', 'set', ...cut, '-resize', `x${height}`, '-statistic', 'Median', '3', tmp]);
const png = PNG.sync.read(readFileSync(tmp));
const imgd = { width: png.width, height: png.height, data: new Uint8ClampedArray(png.data) };
// hard alpha: anything mostly transparent is background
// (transparent pixels get a colour no dog has, so they don't share a palette entry with his black coat)
for (let i = 0; i < imgd.data.length; i += 4) {
  if (imgd.data[i + 3] > 128) imgd.data[i + 3] = 255;
  else { imgd.data[i] = 255; imgd.data[i + 1] = 0; imgd.data[i + 2] = 255; imgd.data[i + 3] = 0; }
}
const options = { numberofcolors: +colours, colorquantcycles: 4, colorsampling: 2, pathomit: 10, ltres: 1, qtres: 1, roundcoords: 0, blurradius: 0, strokewidth: 0, linefilter: true, mincolorratio: 0 };
const svg = ImageTracer.imagedataToSVG(imgd, options);
const paths = [];
for (const m of svg.matchAll(/<path fill="rgb\((\d+),(\d+),(\d+)\)"[^>]*?opacity="([\d.]+)"[^>]*?d="([^"]+)"/g)) {
  const [, r, g, b, a, d] = m;
  if (+a < 0.5) continue; // the transparent background colour
  const hex = '#' + [r, g, b].map((v) => (+v).toString(16).padStart(2, '0')).join('');
  paths.push([hex, d.trim().replace(/\s+/g, ' ')]);
}
mkdirSync(join(root, 'src/vector/traced'), { recursive: true });
const out = join(root, `src/vector/traced/${name}.js`);
writeFileSync(out, `// Generated by scripts/trace.mjs from ${input.split('/').pop()}; do not edit by hand.\nexport default ${JSON.stringify({ w: png.width, h: png.height, paths })};\n`);
console.log(`${out}: ${paths.length} paths, ${(readFileSync(out).length / 1024).toFixed(0)} KB, ${png.width}x${png.height}`);
