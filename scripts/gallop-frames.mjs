// Renders one stride of the 3D dog's gallop (tests/gallop.html through Vite) into PNG frames and
// traces each into vector shapes: src/vector/traced/gallop.js (maintainers only; output committed).
//   node scripts/gallop-frames.mjs [frames=12] [colours=10]
import { createServer } from 'vite';
import { chromium } from 'playwright';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const [n = '12', colours = '10'] = process.argv.slice(2);
const server = await createServer({ root, configFile: false, server: { host: '127.0.0.1', port: 5219, strictPort: true }, logLevel: 'error' });
await server.listen();
const browser = await chromium.launch({ args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 720, height: 440 } });
await page.goto('http://127.0.0.1:5219/tests/gallop.html');
await page.waitForFunction(() => window.ready, null, { timeout: 60000 });
const cycle = await page.evaluate(() => window.cycle);
const dir = mkdtempSync(join(tmpdir(), 'spot-gallop-'));
const frames = [];
for (let i = 0; i < +n; i++) {
  await page.evaluate((dt) => window.step(dt), cycle / +n);
  const png = join(dir, `f${String(i).padStart(2, '0')}.png`);
  await page.locator('canvas').screenshot({ path: png, omitBackground: true });
  // trace with the same tool as the portrait; white background is not needed (alpha already)
  execFileSync('node', [join(root, 'scripts/trace.mjs'), png, `_frame`, '440', colours, '0'], { stdio: 'pipe', env: { ...process.env, KEEP_FRAME: '1' } });
  const mod = readFileSync(join(root, 'src/vector/traced/_frame.js'), 'utf8');
  frames.push(JSON.parse(mod.slice(mod.indexOf('{'), mod.lastIndexOf('}') + 1)));
}
await browser.close();
await server.close();
execFileSync('rm', [join(root, 'src/vector/traced/_frame.js')]);
const out = join(root, 'src/vector/traced/gallop.js');
writeFileSync(out, `// Generated by scripts/gallop-frames.mjs: one gallop stride of the 3D dog, traced; do not edit by hand.\nexport default ${JSON.stringify({ frames })};\n`);
console.log(`${out}: ${frames.length} frames, ${(readFileSync(out).length / 1024).toFixed(0)} KB (${frames.map((f) => f.w + 'x' + f.h).join(' ')})`);
